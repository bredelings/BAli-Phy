-- component would discard their relative rates. The likelihood scales the whole mixture.
-- Bio++ agrees up to rounding; differences from IQ-TREE remain unresolved.
-- The UL2 parameter set also differs from the rates reported in the paper
-- (Le, Lartillot & Gascuel 2008, Table 3); we follow PhyloBayes consistently.
